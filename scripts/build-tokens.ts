/**
 * design/tokens.json (Figma export) -> src/styles/tokens.css (Tailwind v4 @theme).
 *
 * Naming (Figma -> CSS var -> utility):
 *   color/primary/600      -> --color-primary-600      -> bg-primary-600
 *   semantic/text/primary  -> --color-text-primary     -> text-text-primary   (aliases stay var() references)
 *   space/16               -> --spacing: 1px            -> p-16 = 16px (utility number = Figma token number)
 *   radius/lg              -> --radius-lg               -> rounded-lg
 *   BCC/Body 1 Semi Bold   -> --text-body-1-semibold    -> text-body-1-semibold (size + line height + tracking + weight)
 *   BCC/Shadow card        -> --shadow-card             -> shadow-card
 *
 * Tailwind's default palette, type scale, radii and shadows are reset, so only Figma tokens exist.
 * Usage: pnpm tokens          (write)
 *        pnpm tokens --check  (CI: fail if tokens.css is stale)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

interface Variable {
  name: string;
  type: 'COLOR' | 'FLOAT' | 'STRING' | 'BOOLEAN';
  value: string | number | boolean;
  alias: string | null;
}

interface TextStyle {
  name: string;
  family: string;
  style: string;
  size: number;
  lineHeight: { unit: 'PERCENT' | 'PIXELS' | 'AUTO'; value?: number };
  letterSpacing: { unit: 'PERCENT' | 'PIXELS'; value: number };
}

interface EffectStyle {
  name: string;
  effects: {
    type: string;
    color: string | null;
    x: number;
    y: number;
    radius: number;
    spread: number;
  }[];
}

interface TokensFile {
  collections: { name: string; vars: Variable[] }[];
  textStyles: TextStyle[];
  effectStyles: EffectStyle[];
}

const ROOT = process.cwd();
const SOURCE = join(ROOT, 'design/tokens.json');
const TARGET = join(ROOT, 'src/styles/tokens.css');

const FONT_WEIGHTS: Record<string, number> = {
  Regular: 400,
  Medium: 500,
  'Semi Bold': 600,
  Bold: 700,
};

const round = (value: number, digits = 4): number => Number(value.toFixed(digits));

export function colorVarName(figmaName: string): string {
  const parts = figmaName.split('/');
  // color/primary/600 -> primary-600 ; semantic/text/primary -> text-primary
  return `--color-${parts.slice(1).join('-')}`;
}

export function textStyleName(figmaName: string): string {
  return figmaName
    .replace(/^BCC\//, '')
    .replace(/Semi Bold/g, 'semibold')
    .trim()
    .toLowerCase()
    .replace(/\s+/g, '-');
}

export function effectName(figmaName: string): string {
  return figmaName
    .replace(/^BCC\/Shadow\s+/, '')
    .trim()
    .toLowerCase()
    .replace(/\s+/g, '-');
}

export function buildCss(tokens: TokensFile): string {
  const vars = tokens.collections.flatMap((c) => c.vars);
  const lines: string[] = [];
  const push = (line = '') => lines.push(line);

  push(
    '/* GENERATED by scripts/build-tokens.ts from design/tokens.json (Figma "BCC / Foundations"). Do not edit. */',
  );
  push();
  push('@theme {');
  push('  /* Reset Tailwind defaults: only Figma tokens are available. */');
  push('  --color-*: initial;');
  push('  --text-*: initial;');
  push('  --radius-*: initial;');
  push('  --shadow-*: initial;');
  push('  --font-weight-*: initial;');
  push();
  push('  --font-sans: var(--font-inter), ui-sans-serif, system-ui, sans-serif;');
  push('  /* 1 spacing unit = 1px, so `p-16` is Figma space/16. */');
  push('  --spacing: 1px;');
  push();

  push('  /* Colors: primitives */');
  vars
    .filter((v) => v.type === 'COLOR' && v.name.startsWith('color/'))
    .forEach((v) => {
      push(`  ${colorVarName(v.name)}: ${String(v.value)};`);
    });
  push();
  push('  /* Colors: semantic (aliases of primitives) */');
  vars
    .filter((v) => v.type === 'COLOR' && v.name.startsWith('semantic/'))
    .forEach((v) => {
      const value = v.alias ? `var(${colorVarName(v.alias)})` : String(v.value);
      push(`  ${colorVarName(v.name)}: ${value};`);
    });
  push();

  push('  /* Spacing tokens (also usable as var(--space-*)) */');
  vars
    .filter((v) => v.name.startsWith('space/'))
    .forEach((v) => {
      push(`  --space-${v.name.split('/')[1] ?? ''}: ${String(v.value)}px;`);
    });
  push();

  push('  /* Radius */');
  vars
    .filter((v) => v.name.startsWith('radius/'))
    .forEach((v) => {
      push(`  --radius-${v.name.split('/')[1] ?? ''}: ${String(v.value)}px;`);
    });
  push();

  push('  /* Font weights used by the BCC text styles */');
  [...new Set(tokens.textStyles.map((s) => s.style))].forEach((style) => {
    const weight = FONT_WEIGHTS[style];
    if (weight === undefined) throw new Error(`Unknown font style "${style}"`);
    push(`  --font-weight-${style.toLowerCase().replace(/\s+/g, '')}: ${weight};`);
  });
  push();

  push('  /* Text styles (BCC/…) */');
  tokens.textStyles.forEach((s) => {
    const name = textStyleName(s.name);
    const weight = FONT_WEIGHTS[s.style];
    if (weight === undefined) throw new Error(`Unknown font style "${s.style}" in ${s.name}`);
    const lineHeight =
      s.lineHeight.unit === 'PERCENT' && s.lineHeight.value !== undefined
        ? String(round(s.lineHeight.value / 100, 3))
        : s.lineHeight.unit === 'PIXELS' && s.lineHeight.value !== undefined
          ? `${s.lineHeight.value}px`
          : 'normal';
    const tracking =
      s.letterSpacing.unit === 'PERCENT'
        ? `${round(s.letterSpacing.value / 100)}em`
        : `${s.letterSpacing.value}px`;
    push(`  --text-${name}: ${s.size}px;`);
    push(`  --text-${name}--line-height: ${lineHeight};`);
    push(`  --text-${name}--letter-spacing: ${tracking};`);
    push(`  --text-${name}--font-weight: ${weight};`);
  });
  push();

  push('  /* Shadows (BCC/Shadow …) */');
  tokens.effectStyles.forEach((s) => {
    const value = s.effects
      .filter((e) => e.type === 'DROP_SHADOW' && e.color)
      .map((e) => `${e.x}px ${e.y}px ${e.radius}px ${e.spread}px ${e.color ?? ''}`)
      .join(', ');
    push(`  --shadow-${effectName(s.name)}: ${value};`);
  });
  push('}');
  push();
  return lines.join('\n');
}

function main(): void {
  const tokens = JSON.parse(readFileSync(SOURCE, 'utf8')) as TokensFile;
  const css = buildCss(tokens);
  if (process.argv.includes('--check')) {
    const current = readFileSync(TARGET, 'utf8');
    if (current !== css) {
      console.error('tokens.css is out of date. Run `pnpm tokens`.');
      process.exit(1);
    }
    console.log('tokens.css is up to date.');
    return;
  }
  writeFileSync(TARGET, css);
  console.log(`Wrote ${TARGET}`);
}

main();
